    private const BindingFlags Declared = BindingFlags.DeclaredOnly | BindingFlags.Instance |
        BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic;
    private const BindingFlags InstanceConstructors = BindingFlags.DeclaredOnly | BindingFlags.Instance |
        BindingFlags.Public | BindingFlags.NonPublic;

    [Test]
    public void LocalisedOwnerKeepsWholeTypeAndOrderedOptionsWithoutConstruction()
    {
        Type owner = typeof(LocalisedUIString);
        Assert.AreEqual("HLLocalisation.Runtime", owner.Assembly.GetName().Name);
        Assert.AreEqual("Hardlight.Localisation.LocalisedUIString", owner.FullName);
        Assert.AreEqual("Hardlight.Localisation", owner.Namespace);
        Assert.AreEqual(1048577, (int)owner.Attributes);
        Assert.AreEqual(typeof(MonoBehaviour), owner.BaseType);
        Assert.AreEqual("UnityEngine.CoreModule", owner.BaseType.Assembly.GetName().Name);
        Assert.IsFalse(owner.IsGenericType);
        Assert.IsNull(owner.DeclaringType);
        Assert.IsNull(owner.TypeInitializer);
        Assert.AreEqual(0, owner.GetNestedTypes(Declared).Length);
        Assert.AreEqual(0, owner.GetInterfaces().Length);
        Assert.AreEqual(0, owner.GetEvents(Declared).Length);
        Assert.AreEqual(6, owner.GetFields(Declared).Length);
        Assert.AreEqual(9, owner.GetMethods(Declared).Length);
        Assert.AreEqual(1, owner.GetProperties(Declared).Length);
        IList<CustomAttributeData> attributes = owner.GetCustomAttributesData();
        Assert.AreEqual(3, attributes.Count);
        Option[] orderedOptions = { Option.ArrayBoundsChecks, Option.NullChecks };
        for (int i = 0; i < orderedOptions.Length; i++)
        {
            CustomAttributeData option = attributes[i];
            Assert.AreEqual(typeof(Il2CppSetOptionAttribute), option.AttributeType);
            Assert.AreEqual("HLUnityCore.Runtime", option.AttributeType.Assembly.GetName().Name);
            CollectionAssert.AreEqual(new[] { typeof(Option), typeof(object) }, option.Constructor.GetParameters().Select(p => p.ParameterType).ToArray());
            Assert.AreEqual(2, option.ConstructorArguments.Count);
            Assert.AreEqual(typeof(Option), option.ConstructorArguments[0].ArgumentType);
            Assert.AreEqual((int)orderedOptions[i], Convert.ToInt32(option.ConstructorArguments[0].Value));
            Assert.AreEqual(typeof(bool), option.ConstructorArguments[1].ArgumentType);
            Assert.AreEqual(false, option.ConstructorArguments[1].Value);
            Assert.AreEqual(0, option.NamedArguments.Count);
        }
        EmptyAttribute(attributes[2], typeof(DisallowMultipleComponent), "UnityEngine.CoreModule");
        ConstructorInfo constructor = owner.GetConstructors(InstanceConstructors).Single();
        Assert.AreEqual(6278, (int)constructor.Attributes);
        Assert.AreEqual(0, (int)constructor.GetMethodImplementationFlags());
        Assert.AreEqual(0, constructor.GetParameters().Length);
        Assert.AreEqual(0, constructor.GetCustomAttributesData().Count);
        // Metadata only. No instance, constructor, attribute constructor, lifecycle,
        // string-table callback, font, material, text target or provider API runs.
    }

    [Test]
    public void LocalisedFieldsKeepExactTargetTypesAndHashEnumSerializationOrder()
    {
        Type owner = typeof(LocalisedUIString);
        FieldInfo[] fields = owner.GetFields(Declared).OrderBy(f => f.MetadataToken).ToArray();
        string[] names = { "m_identifier", "m_uguiTextTarget", "m_tmpUguiTextTarget", "m_tmpRTLTextTarget", "m_tmpTextTarget", "m_dirty" };
        Type[] types = { typeof(Strings), typeof(Text), typeof(TextMeshProUGUI), typeof(RTLTextMeshPro), typeof(TextMeshPro), typeof(bool) };
        string[] assemblies = { "HLAutoGenerated", "UnityEngine.UI", "Unity.TextMeshPro", "HLRTLTextMeshPro.Runtime", "Unity.TextMeshPro", "mscorlib" };
        Assert.AreEqual(6, fields.Length);
        for (int i = 0; i < fields.Length; i++)
        {
            FieldInfo field = fields[i];
            Assert.AreEqual(names[i], field.Name);
            Assert.AreEqual(types[i], field.FieldType);
            Assert.AreEqual(assemblies[i], field.FieldType.Assembly.GetName().Name);
            Assert.AreEqual(1, (int)field.Attributes);
            Assert.IsFalse(field.IsStatic);
            Assert.IsFalse(field.IsInitOnly);
            Assert.IsFalse(field.IsLiteral);
            Assert.IsFalse(field.IsNotSerialized);
            IList<CustomAttributeData> attributes = field.GetCustomAttributesData();
            if (i == 0)
            {
                Assert.AreEqual(2, attributes.Count);
                CustomAttributeData hash = attributes[0];
                Assert.AreEqual(typeof(HashEnumAttribute), hash.AttributeType);
                Assert.AreEqual("HLUnityCore.Runtime", hash.AttributeType.Assembly.GetName().Name);
                CollectionAssert.AreEqual(new[] { typeof(Type) }, hash.Constructor.GetParameters().Select(p => p.ParameterType).ToArray());
                Assert.AreEqual(1, hash.ConstructorArguments.Count);
                Assert.AreEqual(typeof(Type), hash.ConstructorArguments[0].ArgumentType);
                Assert.AreEqual(typeof(Strings), hash.ConstructorArguments[0].Value);
                Assert.AreEqual(0, hash.NamedArguments.Count);
                EmptyAttribute(attributes[1], typeof(SerializeField), "UnityEngine.CoreModule");
            }
            else if (i < 5)
            {
                Assert.AreEqual(1, attributes.Count);
                EmptyAttribute(attributes[0], typeof(SerializeField), "UnityEngine.CoreModule");
            }
            else Assert.AreEqual(0, attributes.Count);
        }
        // NONE is a literal enum constant; the original constructor still uses
        // the ordinary zero default. Neither any instance nor field value is read.
        Assert.AreEqual(unchecked((int)0xb6fa1284), (int)Strings.NONE);
    }

    [Test]
    public void LocalisedMethodsKeepPublicLifecycleAndExactNullOverrideContract()
    {
        Type owner = typeof(LocalisedUIString);
        MethodInfo[] methods = owner.GetMethods(Declared).OrderBy(m => m.MetadataToken).ToArray();
        string[] names = { "MakeDirty", "get_Identifier", "set_Identifier", "OnEnable", "OnDisable", "Update", "FindTextTargets", "UpdateString", "GetLocalisedText" };
        int[] flags = { 134, 2182, 2182, 134, 134, 134, 134, 134, 129 };
        Type[] results = { typeof(void), typeof(Strings), typeof(void), typeof(void), typeof(void), typeof(void), typeof(void), typeof(void), typeof(string) };
        Assert.AreEqual(9, methods.Length);
        for (int i = 0; i < methods.Length; i++)
        {
            MethodInfo method = methods[i];
            Assert.AreEqual(names[i], method.Name);
            Assert.AreEqual(flags[i], (int)method.Attributes);
            Assert.AreEqual(0, (int)method.GetMethodImplementationFlags());
            Assert.AreEqual(results[i], method.ReturnType);
            Assert.IsFalse(method.IsGenericMethod);
            Assert.IsFalse(method.IsVirtual);
            Assert.IsFalse(method.IsStatic);
            Assert.AreEqual(0, method.GetCustomAttributesData().Count);
            Assert.AreEqual(0, method.ReturnParameter.GetCustomAttributesData().Count);
            ParameterInfo[] parameters = method.GetParameters();
            if (i == 2)
            {
                Assert.AreEqual(1, parameters.Length);
                Parameter(parameters[0], "value", typeof(Strings), 0);
                Assert.IsFalse(parameters[0].HasDefaultValue);
            }
            else if (i == 7)
            {
                Assert.AreEqual(1, parameters.Length);
                Parameter(parameters[0], "overrideString", typeof(string), 4112);
                Assert.IsTrue(parameters[0].IsOptional);
                Assert.IsTrue(parameters[0].HasDefaultValue);
                Assert.IsNull(parameters[0].DefaultValue);
                Assert.IsNull(parameters[0].RawDefaultValue);
            }
            else Assert.AreEqual(0, parameters.Length);
        }
        PropertyInfo property = owner.GetProperties(Declared).Single();
        Assert.AreEqual("Identifier", property.Name);
        Assert.AreEqual(typeof(Strings), property.PropertyType);
        Assert.AreEqual(0, (int)property.Attributes);
        Assert.AreEqual(0, property.GetIndexParameters().Length);
        Assert.AreEqual(0, property.GetCustomAttributesData().Count);
        Assert.AreEqual(methods[1], property.GetGetMethod(true));
        Assert.AreEqual(methods[2], property.GetSetMethod(true));
        // Shipping nil return Param rows and Mono synthetic Retval flags have
        // distinct transport roles. The result type/empty return CAD is checked;
        // reflection ReturnParameter.Attributes is deliberately not equated.
    }

    private static void Parameter(ParameterInfo parameter, string name, Type type, int flags)
    {
        Assert.AreEqual(name, parameter.Name);
        Assert.AreEqual(type, parameter.ParameterType);
        Assert.AreEqual(flags, (int)parameter.Attributes);
        IList<CustomAttributeData> attributes = parameter.GetCustomAttributesData();
        if (flags == 0) Assert.AreEqual(0, attributes.Count);
        else
        {
            Assert.AreEqual(4112, flags);
            Assert.AreEqual(1, attributes.Count);
            EmptyAttribute(attributes[0], typeof(System.Runtime.InteropServices.OptionalAttribute), "mscorlib");
        }
    }

    private static void EmptyAttribute(CustomAttributeData attribute, Type type, string assembly)
    {
        Assert.AreEqual(type, attribute.AttributeType);
        Assert.AreEqual(assembly, attribute.AttributeType.Assembly.GetName().Name);
        Assert.AreEqual(0, attribute.Constructor.GetParameters().Length);
        Assert.AreEqual(0, attribute.ConstructorArguments.Count);
        Assert.AreEqual(0, attribute.NamedArguments.Count);
    }
}
