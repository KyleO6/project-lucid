        [Test]
        public void OriginalConfigurationDeclarationsRetainScopedFieldsMethodsAndAnnotations()
        {
            Type build = typeof(BuildValidationConfiguration);
            Type features = typeof(PreprocessorDirectiveConfiguration);
            Type lookup = typeof(BuildValidationConfiguration.ErrorSeverityLookup);
            Assert.That(build.Assembly.GetName().Name, Is.EqualTo("Game.Runtime"));
            Assert.That(features.Assembly, Is.SameAs(build.Assembly));
            Assert.That(build.BaseType, Is.SameAs(typeof(SystemConfigurationAsset)));
            Assert.That(features.BaseType, Is.SameAs(typeof(SystemConfigurationAsset)));
            Assert.That(typeof(ValidationErrorTypes).Assembly.GetName().Name, Is.EqualTo("HLAutoGenerated"));
            Assert.That(typeof(ValidationErrorSeverity).Assembly, Is.SameAs(typeof(ValidationErrorTypes).Assembly));
            Assert.That(typeof(BuildFeatures).Assembly, Is.SameAs(typeof(ValidationErrorTypes).Assembly));
            Assert.That(build.Attributes, Is.EqualTo(TypeAttributes.Public | TypeAttributes.BeforeFieldInit));
            Assert.That(features.Attributes, Is.EqualTo(TypeAttributes.Public | TypeAttributes.BeforeFieldInit));
            Assert.That(lookup.DeclaringType, Is.SameAs(build));
            Assert.That(lookup.Attributes, Is.EqualTo(TypeAttributes.NestedPublic | TypeAttributes.Serializable | TypeAttributes.BeforeFieldInit));
            // Serializable is an original TypeDef flag. Physical-CAD absence is
            // qualified separately in original/current PE, without a reflection oracle.
            Type[] nested = build.GetNestedTypes(Own);
            Assert.That(nested.Length, Is.EqualTo(2));
            Type capture = null;
            foreach (Type candidate in nested)
                if (candidate != lookup)
                {
                    Assert.That(capture, Is.Null);
                    capture = candidate;
                }
            Assert.That(capture, Is.Not.Null);
            Assert.That(capture.DeclaringType, Is.SameAs(build));
            Assert.That(capture.Attributes, Is.EqualTo(TypeAttributes.NestedPrivate | TypeAttributes.Sealed | TypeAttributes.BeforeFieldInit));
            Assert.That(capture.Name.StartsWith("<>c__DisplayClass", StringComparison.Ordinal), Is.True);
            AssertCad(capture, typeof(CompilerGeneratedAttribute));
            AssertField(capture, "errorType", typeof(ValidationErrorTypes), FieldAttributes.Public);
            Assert.That(capture.GetFields(Own).Length, Is.EqualTo(1));
            MethodInfo[] predicates = capture.GetMethods(Own);
            Assert.That(predicates.Length, Is.EqualTo(1));
            Assert.That(predicates[0].Name.StartsWith("<GetSeverity>b__", StringComparison.Ordinal), Is.True);
            AssertSignature(predicates[0], typeof(bool), typeof(BuildValidationConfiguration.ErrorSeverityLookup));
            Assert.That(predicates[0].Attributes, Is.EqualTo(MethodAttributes.Assembly | MethodAttributes.HideBySig));
            AssertCad(predicates[0]);
            Assert.That(capture.GetConstructors(Own).Length, Is.EqualTo(1));

            Assert.That(build.GetFields(Own).Length, Is.EqualTo(11));
            Assert.That(features.GetFields(Own).Length, Is.EqualTo(3));
            Assert.That(lookup.GetFields(Own).Length, Is.EqualTo(2));
            AssertField(build, "AssetMenu", typeof(string), FieldAttributes.Public | FieldAttributes.Static | FieldAttributes.Literal | FieldAttributes.HasDefault);
            AssertField(build, "DefaultErrorSeverity", typeof(ValidationErrorSeverity), FieldAttributes.Public | FieldAttributes.Static | FieldAttributes.Literal | FieldAttributes.HasDefault);
            Assert.That(build.GetField("AssetMenu", Own).GetRawConstantValue(), Is.EqualTo("HardlightProject/Config/"));
            Assert.That(build.GetField("DefaultErrorSeverity", Own).GetRawConstantValue(), Is.EqualTo(1433829694));
            foreach (string name in new[] { "m_validatePrefabs", "m_validateScenes" })
                AssertField(build, name, typeof(bool), FieldAttributes.Private, typeof(SerializeField));
            AssertField(build, "m_warnOnPrefabErrors", typeof(bool), FieldAttributes.Private, typeof(TooltipAttribute), typeof(SerializeField), typeof(ShowIfAttribute));
            AssertField(build, "m_warnOnSceneErrors", typeof(bool), FieldAttributes.Private, typeof(TooltipAttribute), typeof(ShowIfAttribute), typeof(SerializeField));
            foreach (string name in new[] { "m_excludedPrefabPaths", "m_excludedScenePaths" })
                AssertField(build, name, typeof(string[]), FieldAttributes.Private, typeof(SerializeField));
            AssertField(build, "m_resultOutputPath", typeof(string), FieldAttributes.Private, typeof(SerializeField));
            AssertField(build, "m_validationFailAtSeverityLevel", typeof(List<ValidationErrorSeverity>), FieldAttributes.Public, typeof(SerializeField), typeof(TooltipAttribute));
            AssertField(build, "m_errorSeverityLookups", typeof(List<BuildValidationConfiguration.ErrorSeverityLookup>), FieldAttributes.Private, typeof(TooltipAttribute), typeof(SerializeField));
            AssertField(lookup, "m_errorType", typeof(ValidationErrorTypes), FieldAttributes.Private, typeof(SerializeField));
            AssertField(lookup, "m_errorSeverity", typeof(ValidationErrorSeverity), FieldAttributes.Private, typeof(SerializeField));
            AssertField(features, "m_buildFeatures", typeof(BuildFeatures[]), FieldAttributes.Private, typeof(SerializeField));
            AssertField(features, "m_additionalBuildFeatures", typeof(BuildFeatures[]), FieldAttributes.Private, typeof(SerializeField));
            AssertField(features, "m_allBuildFeatures", typeof(List<BuildFeatures>), FieldAttributes.Private | FieldAttributes.InitOnly);

            Assert.That(build.GetMethods(Own).Length + build.GetConstructors(Own).Length, Is.EqualTo(11));
            Assert.That(features.GetMethods(Own).Length + features.GetConstructors(Own).Length, Is.EqualTo(3));
            Assert.That(lookup.GetMethods(Own).Length + lookup.GetConstructors(Own).Length, Is.EqualTo(3));
            MethodAttributes getterFlags = MethodAttributes.Public | MethodAttributes.HideBySig | MethodAttributes.SpecialName;
            foreach (string name in new[] { "get_ValidatePrefabs", "get_WarnOnPrefabErrors", "get_ValidateScenes", "get_WarnOnSceneErrors" })
                AssertMethod(build, name, typeof(bool), getterFlags);
            AssertMethod(build, "get_ExcludedPrefabPaths", typeof(string[]), getterFlags);
            AssertMethod(build, "get_ResultOutputPath", typeof(string), getterFlags);
            AssertMethod(lookup, "get_ErrorType", typeof(ValidationErrorTypes), getterFlags);
            AssertMethod(lookup, "get_Severity", typeof(ValidationErrorSeverity), getterFlags);
            AssertMethod(build, "IsValidationFail", typeof(bool), MethodAttributes.Public | MethodAttributes.HideBySig, typeof(ValidationErrorTypes));
            AssertMethod(build, "GetSeverity", typeof(ValidationErrorSeverity), MethodAttributes.Public | MethodAttributes.HideBySig, typeof(ValidationErrorTypes));
            AssertMethod(build, "ShouldValidateScene", typeof(bool), MethodAttributes.Public | MethodAttributes.HideBySig, typeof(string));
            AssertMethod(build, "Validate", typeof(void), MethodAttributes.Public | MethodAttributes.HideBySig | MethodAttributes.Virtual);
            AssertMethod(features, "GetBuildFeatures", typeof(ReadOnlyCollection<BuildFeatures>), MethodAttributes.Public | MethodAttributes.HideBySig);
            AssertMethod(features, "Validate", typeof(void), MethodAttributes.Public | MethodAttributes.HideBySig | MethodAttributes.Virtual);
            foreach (Type owner in new[] { build, features, lookup, capture })
                AssertConstructor(owner);
            Assert.That(build.GetProperties(Own).Length, Is.EqualTo(6));
            Assert.That(lookup.GetProperties(Own).Length, Is.EqualTo(2));
            AssertSignature(build.GetMethod("IsValidationFail", Own), typeof(bool), typeof(ValidationErrorTypes));
            AssertSignature(build.GetMethod("GetSeverity", Own), typeof(ValidationErrorSeverity), typeof(ValidationErrorTypes));
            AssertSignature(build.GetMethod("ShouldValidateScene", Own), typeof(bool), typeof(string));
            AssertSignature(features.GetMethod("GetBuildFeatures", Own), typeof(ReadOnlyCollection<BuildFeatures>));
            Assert.That(build.GetMethod("Validate", Own).GetBaseDefinition().DeclaringType, Is.SameAs(typeof(SystemConfigurationAsset)));
            Assert.That(features.GetMethod("Validate", Own).GetBaseDefinition().DeclaringType, Is.SameAs(typeof(SystemConfigurationAsset)));
            AssertCad(build, typeof(Il2CppSetOptionAttribute), typeof(Il2CppSetOptionAttribute), typeof(CreateAssetMenuAttribute));
            AssertCad(features, typeof(CreateAssetMenuAttribute));
            IList<CustomAttributeData> buildCad = build.GetCustomAttributesData();
            Assert.That(buildCad[0].ConstructorArguments[0].ArgumentType, Is.SameAs(typeof(Option)));
            Assert.That(buildCad[0].ConstructorArguments[0].Value, Is.EqualTo((int)Option.NullChecks));
            Assert.That(buildCad[0].ConstructorArguments[1].Value, Is.EqualTo(false));
            Assert.That(buildCad[1].ConstructorArguments[0].Value, Is.EqualTo((int)Option.ArrayBoundsChecks));
            Assert.That(buildCad[1].ConstructorArguments[1].Value, Is.EqualTo(false));
            AssertMenu(buildCad[2], "BuildValidationConfiguration", "HardlightProject/Config/Build Validation");
            AssertMenu(features.GetCustomAttributesData()[0], "PreprocessorDirectiveConfiguration", "HardlightProject/Config/PreprocessorDirectiveConfiguration");
            AssertConditional(build.GetField("m_warnOnPrefabErrors", Own).GetCustomAttributesData()[2], "m_validatePrefabs");
            AssertConditional(build.GetField("m_warnOnSceneErrors", Own).GetCustomAttributesData()[1], "m_validateScenes");
        }

        [Test]
        public void OwnedSeverityLookupKeepsFirstMatchFallbackAndPublicFailureLevels()
        {
            Owned<BuildValidationConfiguration>(config =>
            {
                Assert.That(config.ExcludedPrefabPaths, Is.Null);
                Assert.That(config.ResultOutputPath, Is.Empty);
                Assert.That(config.ValidatePrefabs, Is.False);
                Assert.That(config.ValidateScenes, Is.False);
                Assert.That(config.GetSeverity(ValidationErrorTypes.Collider), Is.EqualTo(ValidationErrorSeverity.Error));
                Assert.That(config.IsValidationFail(ValidationErrorTypes.Collider), Is.False);
                using (SerializedObject serialized = new SerializedObject(config))
                {
                    SerializedProperty entries = Property(serialized, "m_errorSeverityLookups");
                    entries.arraySize = 3;
                    SetLookup(entries.GetArrayElementAtIndex(0), ValidationErrorTypes.Collider, ValidationErrorSeverity.Warning);
                    SetLookup(entries.GetArrayElementAtIndex(1), ValidationErrorTypes.Collider, ValidationErrorSeverity.Exception);
                    SetLookup(entries.GetArrayElementAtIndex(2), ValidationErrorTypes.Audio, ValidationErrorSeverity.Log);
                    Assert.That(serialized.ApplyModifiedPropertiesWithoutUndo(), Is.True);
                }
                Assert.That(config.GetSeverity(ValidationErrorTypes.Collider), Is.EqualTo(ValidationErrorSeverity.Warning));
                Assert.That(config.GetSeverity(ValidationErrorTypes.Audio), Is.EqualTo(ValidationErrorSeverity.Log));
                Assert.That(config.GetSeverity(ValidationErrorTypes.Generic), Is.EqualTo(ValidationErrorSeverity.Error));
                config.m_validationFailAtSeverityLevel.Add(ValidationErrorSeverity.Warning);
                config.m_validationFailAtSeverityLevel.Add(ValidationErrorSeverity.Error);
                Assert.That(config.IsValidationFail(ValidationErrorTypes.Collider), Is.True);
                Assert.That(config.IsValidationFail(ValidationErrorTypes.Generic), Is.True);
                Assert.That(config.IsValidationFail(ValidationErrorTypes.Audio), Is.False);
                // Public owned input, with no reflected or private field write.
                config.m_validationFailAtSeverityLevel = null;
                Assert.That(config.GetSeverity(ValidationErrorTypes.Generic), Is.EqualTo(ValidationErrorSeverity.Error));
                Assert.Throws<NullReferenceException>(() => config.IsValidationFail(ValidationErrorTypes.Generic));
                config.Validate();
            });
        }

        [Test]
        public void OwnedSceneExclusionsUseOrderedCaseSensitiveSubstringsAndBlankRejection()
        {
            Owned<BuildValidationConfiguration>(config =>
            {
                Assert.That(config.ShouldValidateScene(null), Is.False);
                Assert.That(config.ShouldValidateScene("  \t\r\n"), Is.False);
                Assert.That(config.ShouldValidateScene("Assets/s_BossGate.unity"), Is.True);
                using (SerializedObject serialized = new SerializedObject(config))
                {
                    Property(serialized, "m_validateScenes").boolValue = false;
                    SetStrings(Property(serialized, "m_excludedScenePaths"), "Boss", "Excluded/");
                    Assert.That(serialized.ApplyModifiedPropertiesWithoutUndo(), Is.True);
                }
                Assert.That(config.ShouldValidateScene("Assets/s_BossGate.unity"), Is.False);
                Assert.That(config.ShouldValidateScene("Assets/s_bossGate.unity"), Is.True);
                Assert.That(config.ShouldValidateScene("Assets/Excluded/s_act.unity"), Is.False);
                Assert.That(config.ShouldValidateScene("Assets/s_act.unity"), Is.True);
                using (SerializedObject serialized = new SerializedObject(config))
                {
                    SetStrings(Property(serialized, "m_excludedScenePaths"), "");
                    Assert.That(serialized.ApplyModifiedPropertiesWithoutUndo(), Is.True);
                }
                Assert.That(config.ShouldValidateScene("Assets/s_act.unity"), Is.False);
                Assert.That(config.ShouldValidateScene(null), Is.False);
                config.Validate();
            });
        }

        [Test]
        public void OwnedBuildFeaturesPreserveOrderDuplicatesAndLiveReadOnlyViews()
        {
            Owned<PreprocessorDirectiveConfiguration>(config =>
            {
                using (SerializedObject serialized = new SerializedObject(config))
                {
                    SetFeatures(Property(serialized, "m_buildFeatures"), BuildFeatures.ASSETBUNDLES, BuildFeatures.GC_ENABLED, BuildFeatures.ASSETBUNDLES);
                    SetFeatures(Property(serialized, "m_additionalBuildFeatures"), BuildFeatures.GC_ENABLED, BuildFeatures.DEBUG_MENU);
                    Assert.That(serialized.ApplyModifiedPropertiesWithoutUndo(), Is.True);
                }
                ReadOnlyCollection<BuildFeatures> first = config.GetBuildFeatures();
                CollectionAssert.AreEqual(new[] { BuildFeatures.ASSETBUNDLES, BuildFeatures.GC_ENABLED, BuildFeatures.ASSETBUNDLES, BuildFeatures.GC_ENABLED, BuildFeatures.DEBUG_MENU }, first);
                Assert.Throws<NotSupportedException>(() => ((IList<BuildFeatures>)first).Add(BuildFeatures.ICLOUD));
                Assert.That(first.Count, Is.EqualTo(5));
                using (SerializedObject serialized = new SerializedObject(config))
                {
                    SetFeatures(Property(serialized, "m_buildFeatures"), BuildFeatures.ICLOUD);
                    SetFeatures(Property(serialized, "m_additionalBuildFeatures"), BuildFeatures.ICLOUD);
                    Assert.That(serialized.ApplyModifiedPropertiesWithoutUndo(), Is.True);
                }
                ReadOnlyCollection<BuildFeatures> second = config.GetBuildFeatures();
                Assert.That(second, Is.Not.SameAs(first));
                CollectionAssert.AreEqual(new[] { BuildFeatures.ICLOUD, BuildFeatures.ICLOUD }, first);
                CollectionAssert.AreEqual(first, second);
                config.Validate();
                CollectionAssert.AreEqual(first, second);
            });
        }

        [Test]
        public void OwnedConstructorFailureAndSerializedApplyKeepTheRealFeatureCache()
        {
            Owned<PreprocessorDirectiveConfiguration>(config =>
            {
                // Fresh construction preserves both original nullable arrays. The
                // first AddRange faults before populating the constructor-owned cache.
                Assert.That(Read<BuildFeatures[]>(config, "m_buildFeatures"), Is.Null);
                Assert.That(Read<BuildFeatures[]>(config, "m_additionalBuildFeatures"), Is.Null);
                List<BuildFeatures> cache = Read<List<BuildFeatures>>(config, "m_allBuildFeatures");
                Assert.That(cache, Is.Not.Null);
                Assert.That(cache.Count, Is.Zero);
                Assert.Throws<ArgumentNullException>(() => config.GetBuildFeatures());
                Assert.That(cache.Count, Is.Zero);
                using (SerializedObject serialized = new SerializedObject(config))
                {
                    SetFeatures(Property(serialized, "m_buildFeatures"), BuildFeatures.ASSETBUNDLES, BuildFeatures.GC_ENABLED);
                    Assert.That(serialized.ApplyModifiedPropertiesWithoutUndo(), Is.True);
                }
                // Unity 2022.3.54f1 also normalizes the untouched serialized array
                // during this apply. This is an Editor transport observation; the
                // original second-AddRange null fault remains a source/native path.
                Assert.That(Read<BuildFeatures[]>(config, "m_additionalBuildFeatures"), Is.Empty);
                Assert.That(Read<List<BuildFeatures>>(config, "m_allBuildFeatures"), Is.SameAs(cache));
                Assert.That(cache.Count, Is.Zero);
                ReadOnlyCollection<BuildFeatures> view = config.GetBuildFeatures();
                Assert.That(Read<List<BuildFeatures>>(config, "m_allBuildFeatures"), Is.SameAs(cache));
                CollectionAssert.AreEqual(new[] { BuildFeatures.ASSETBUNDLES, BuildFeatures.GC_ENABLED }, cache);
                CollectionAssert.AreEqual(cache, view);
            });
        }

        private static void Owned<T>(Action<T> body) where T : ScriptableObject
        {
            T value = null;
            Exception primary = null;
            try
            {
                value = ScriptableObject.CreateInstance<T>();
                Assert.That(value, Is.Not.Null);
                body(value);
            }
            catch (Exception exception)
            {
                primary = exception;
                throw;
            }
            finally
            {
                if (value != null)
                    try { Object.DestroyImmediate(value); }
                    catch (Exception cleanup)
                    {
                        if (primary == null) throw;
                        // Secondary reporting must preserve the active original failure.
                        try { TestContext.Progress.WriteLine("Owned configuration cleanup also failed: " + cleanup); }
                        catch (Exception) { }
                    }
            }
        }

        private static T Read<T>(Object owner, string name)
        {
            FieldInfo field = owner.GetType().GetField(name, Own);
            Assert.That(field, Is.Not.Null);
            Assert.That(field.FieldType, Is.SameAs(typeof(T)));
            return (T)field.GetValue(owner);
        }

        private static SerializedProperty Property(SerializedObject serialized, string name)
        {
            SerializedProperty property = serialized.FindProperty(name);
            Assert.That(property, Is.Not.Null, name);
            return property;
        }

        private static void SetLookup(SerializedProperty item, ValidationErrorTypes type, ValidationErrorSeverity severity)
        {
            SerializedProperty typeField = item.FindPropertyRelative("m_errorType");
            SerializedProperty severityField = item.FindPropertyRelative("m_errorSeverity");
            Assert.That(typeField, Is.Not.Null);
            Assert.That(severityField, Is.Not.Null);
            typeField.intValue = (int)type;
            severityField.intValue = (int)severity;
        }

        private static void SetFeatures(SerializedProperty array, params BuildFeatures[] features)
        {
            array.arraySize = features.Length;
            for (int i = 0; i < features.Length; i++) array.GetArrayElementAtIndex(i).intValue = (int)features[i];
        }

        private static void SetStrings(SerializedProperty array, params string[] values)
        {
            array.arraySize = values.Length;
            for (int i = 0; i < values.Length; i++) array.GetArrayElementAtIndex(i).stringValue = values[i];
        }

        private static void AssertField(Type owner, string name, Type fieldType, FieldAttributes flags, params Type[] cad)
        {
            FieldInfo field = owner.GetField(name, Own);
            Assert.That(field, Is.Not.Null, name);
            Assert.That(field.FieldType, Is.SameAs(fieldType));
            Assert.That(field.Attributes, Is.EqualTo(flags));
            AssertCad(field, cad);
        }

        private static void AssertMethod(Type owner, string name, Type result, MethodAttributes flags, params Type[] arguments)
        {
            MethodInfo method = owner.GetMethod(name, Own);
            AssertSignature(method, result, arguments);
            Assert.That(method.DeclaringType, Is.SameAs(owner));
            Assert.That(method.Attributes, Is.EqualTo(flags));
            AssertCad(method);
        }

        private static void AssertConstructor(Type owner)
        {
            ConstructorInfo[] constructors = owner.GetConstructors(Own);
            Assert.That(constructors.Length, Is.EqualTo(1));
            Assert.That(constructors[0].Attributes, Is.EqualTo(MethodAttributes.Public | MethodAttributes.HideBySig | MethodAttributes.SpecialName | MethodAttributes.RTSpecialName));
            Assert.That(constructors[0].GetParameters().Length, Is.Zero);
            AssertCad(constructors[0]);
        }

        private static void AssertSignature(MethodInfo method, Type result, params Type[] arguments)
        {
            Assert.That(method, Is.Not.Null);
            Assert.That(method.ReturnType, Is.SameAs(result));
            ParameterInfo[] parameters = method.GetParameters();
            Assert.That(parameters.Length, Is.EqualTo(arguments.Length));
            for (int i = 0; i < parameters.Length; i++)
            {
                Assert.That(parameters[i].ParameterType, Is.SameAs(arguments[i]));
                Assert.That(parameters[i].Attributes, Is.EqualTo(ParameterAttributes.None));
                Assert.That(parameters[i].GetCustomAttributesData().Count, Is.Zero);
            }
        }

        private static void AssertCad(MemberInfo member, params Type[] types)
        {
            IList<CustomAttributeData> actual = member.GetCustomAttributesData();
            Assert.That(actual.Count, Is.EqualTo(types.Length), member.Name);
            for (int i = 0; i < types.Length; i++)
            {
                Assert.That(actual[i].AttributeType, Is.SameAs(types[i]));
                Assert.That(actual[i].Constructor.DeclaringType, Is.SameAs(types[i]));
                Assert.That(actual[i].AttributeType.Assembly, Is.SameAs(types[i].Assembly));
            }
        }

        private static void AssertMenu(CustomAttributeData attribute, string fileName, string menuName)
        {
            Assert.That(attribute.ConstructorArguments.Count, Is.Zero);
            Assert.That(attribute.NamedArguments.Count, Is.EqualTo(2));
            Assert.That(attribute.NamedArguments[0].IsField, Is.False);
            Assert.That(attribute.NamedArguments[0].MemberName, Is.EqualTo("fileName"));
            Assert.That(attribute.NamedArguments[0].TypedValue.Value, Is.EqualTo(fileName));
            Assert.That(attribute.NamedArguments[1].IsField, Is.False);
            Assert.That(attribute.NamedArguments[1].MemberName, Is.EqualTo("menuName"));
            Assert.That(attribute.NamedArguments[1].TypedValue.Value, Is.EqualTo(menuName));
        }

        private static void AssertConditional(CustomAttributeData attribute, string fieldName)
        {
            Assert.That(attribute.ConstructorArguments.Count, Is.EqualTo(2));
            Assert.That(attribute.ConstructorArguments[0].ArgumentType, Is.SameAs(typeof(string)));
            Assert.That(attribute.ConstructorArguments[0].Value, Is.EqualTo(fieldName));
            Assert.That(attribute.ConstructorArguments[1].Value, Is.Null);
            Assert.That(attribute.NamedArguments.Count, Is.Zero);
        }
    }
