                    cachedDictionary = BindingUtils.GetMethodValue(cachedMethodInfo, target) as IDictionary;
                cachedKey = Enum.ToObject(KeyType, key);
                cachedBindable = cachedDictionary[cachedKey] as IBindable;
            }
            else
            {
                cachedDictionary = null;
                cachedKey = null;
                if (cachedFieldInfo != null)
                    cachedBindable = cachedFieldInfo.GetValue(target) as IBindable;
                else if (cachedPropertyInfo != null)
                    cachedBindable = (cachedPropertyInfo.CanRead ? cachedPropertyInfo.GetValue(target, null) : null) as IBindable;
