        public static HLSelectable FindSelectable(Vector3 dir, Transform origin, HLSelectable caller, string sceneName)
        {
            Vector3 position = origin.TransformPoint(HLSelectable.GetPointOnRectEdge(origin as RectTransform, Quaternion.Inverse(origin.rotation) * dir));
            return FindSelectable(dir, position, caller, sceneName);
        }

        public static HLSelectable FindSelectable(Vector3 dir, Vector3 position, HLSelectable caller, string sceneName)
        {
            IEnumerable<HLSelectable> selectables = null;
            bool useOverride = false;
            float sameSceneWeighting = 1;
            if (ProcessManager.IsSystemValid<HLSelectableController>())
            {
                HLSelectableController controller = ProcessManager.GetSystem<HLSelectableController>();
                useOverride = controller.UseOverrideList();
                bool block = controller.BlockFindSelectable();
                if (block && !useOverride) return null;
                selectables = controller.m_overrideList.AsReadOnly();
                sameSceneWeighting = controller.m_sameSceneButtonWeighting;
            }
            bool exclusive = false;
            string exclusiveScene = null;
            if (!string.IsNullOrEmpty(sceneName))
            {
                exclusive = s_exclusiveScenes.Contains(sceneName);
                if (exclusive) exclusiveScene = sceneName;
            }
            if (!useOverride) selectables = ActiveSelectables.GetSelectables(exclusiveScene);
            HLSelectable best = null;
            float bestScore = float.NegativeInfinity;
            foreach (HLSelectable selectable in selectables)
            {
                if (selectable == caller) continue;
                if (selectable == null) continue;
                if (!IsValidSelectableForNavigation(selectable)) continue;
                RectTransform rect = selectable.transform as RectTransform;
                Vector3 center = rect != null ? (Vector3)rect.rect.center : Vector3.zero;
                Vector3 candidatePosition = selectable.transform.TransformPoint(center);
                Vector3 delta = candidatePosition - position;
                float dot = Vector3.Dot(dir, delta);
                if (dot <= 0) continue;
                bool callerExists = caller != null;
                float score = dot / delta.sqrMagnitude;
                if (callerExists && !exclusive)
                    score *= caller.SceneName == selectable.SceneName ? sameSceneWeighting : 1;
                if (score > bestScore) { bestScore = score; best = selectable; }
            }
            return best;
        }

        public static bool IsValidSelectableForNavigation(HLSelectable sel)
        {
            if (sel == null) return false;
            if (!sel.IsInteractable()) return false;
            if (sel.Navigation.Mode == HLNavigation.NavMode.None) return false;
            if (!sel.gameObject.activeInHierarchy) return false;
            if (!sel.gameObject.activeSelf) return false;
            if (ProcessManager.IsSystemValid<HLSelectableController>())
            {
                HLSelectableController controller = ProcessManager.GetSystem<HLSelectableController>();
                if (!sel.AnyCornersVisible(controller.BlockFindSelectable())) return false;
            }
            if (sel.NeverSelectable) return false;
            return sel.enabled;
        }

        public bool IsCurrentSelection(HLSelectable selectable) { return m_currentlySelected == selectable; }
        public void DeselectCurrentSelection()
        {
            m_lastKnownSelected = m_currentlySelected;
            if (m_currentlySelected == null) return;
            if (OnDeselect != null) OnDeselect.Invoke(m_currentlySelected);
            m_currentlySelected = null;
            m_inputBridge.DeselectObjectIfCurrentlySelected(m_lastKnownSelected.gameObject);
        }

        public override void SelectThis(SelectableBase selectable, bool instantTransition = false)
        {
            HLSelectable hlSelectable = selectable as HLSelectable;
            if (!m_systemEnabled)
            {
                m_inputBridge.SetSelectedGameObjectWithMemory(hlSelectable.gameObject, null);
                m_currentlySelected = hlSelectable;
                return;
            }
            if (m_currentlySelected == hlSelectable) { HighlightThis(hlSelectable); return; }
            if (!IsValidSelectableForNavigation(hlSelectable)) return;
            DeselectCurrentSelection();
            m_currentlySelected = hlSelectable;
            m_setInstantTransition |= instantTransition | m_forceInstantSelection;
            OnSelect.Invoke(m_currentlySelected);
            m_inputBridge.SetSelectedGameObjectWithMemory(m_currentlySelected.gameObject, null);
        }

        public void HighlightThis(HLSelectable selectable)
        {
            if (!m_systemEnabled || !m_isButtonHighlightActive || !IsValidSelectableForNavigation(selectable)) return;
            this.SafeStopCoroutine(ref m_coroutine);
            m_coroutine = StartCoroutine(MoveToNewParent(selectable));
        }

        public void TrackRecentlySubmittedSelectable(HLSelectable selectable)
        {
            m_lastKnownSelected = m_currentlySelected;
            if (m_recentlySubmittedSelectables.Contains(selectable)) m_recentlySubmittedSelectables.Remove(selectable);
            m_recentlySubmittedSelectables.Add(selectable);
            if (m_recentlySubmittedSelectables.Count > MaxTrackedSubmittedSelectables) m_recentlySubmittedSelectables.RemoveAt(0);
        }

        private IEnumerator MoveToNewParent(HLSelectable selectable)
        {
            if (!m_systemEnabled) yield break;
            if (m_cachedButtonHighlight == null) yield break;
            m_cachedButtonHighlight.transform.SetParent(selectable.HighlightParentTransform, true);
            m_cachedButtonHighlight.SetButtonCanvasLayer(m_buttonHighlightTransitionLayer, 0);
            float timer = 0;
            Transform selectedIndicatorTransform = m_cachedButtonHighlight.transform;
            RectTransform cachedRect = selectedIndicatorTransform as RectTransform;
            if (m_setInstantTransition || m_lastKnownSelected == null ||
                (m_lastKnownSelected != null && !IsValidSelectableForNavigation(m_lastKnownSelected)))
            {
                selectedIndicatorTransform.localScale = m_setInstantTransition ? Vector3.one : Vector3.zero;
                selectedIndicatorTransform.localRotation = Quaternion.identity;
                cachedRect.offsetMin = Vector2.zero;
                cachedRect.offsetMax = Vector2.zero;
                m_cachedButtonHighlight.ResetCanvasLayer();
            }
            Vector3 cachedScale = selectedIndicatorTransform.localScale;
            Quaternion cachedRot = selectedIndicatorTransform.localRotation;
            Vector2 cachedOffsetMin = cachedRect.offsetMin;
            Vector2 cachedOffsetMax = cachedRect.offsetMax;
            Vector3 cachedAnchoredPosition3D = cachedRect.anchoredPosition3D;
            m_cachedButtonHighlight.SetButtonState(selectable.Customisations, false);
            while (timer < m_buttonHighlightTransitionTime)
            {
                timer += Time.unscaledDeltaTime;
                float t = EaseUtilities.Ease(m_movementEasingType, timer / m_buttonHighlightTransitionTime);
                selectedIndicatorTransform.localScale = Vector3.Lerp(cachedScale, Vector3.one, t);
                selectedIndicatorTransform.localRotation = Quaternion.Slerp(cachedRot, Quaternion.identity, t);
                cachedRect.offsetMin = Vector2.Lerp(cachedOffsetMin, Vector2.zero, t);
                cachedRect.offsetMax = Vector2.Lerp(cachedOffsetMax, Vector2.zero, t);
                Vector3 currentPosition = cachedRect.anchoredPosition3D;
                cachedAnchoredPosition3D.x = currentPosition.x;
                cachedAnchoredPosition3D.y = currentPosition.y;
                cachedRect.anchoredPosition3D = Vector3.Lerp(cachedAnchoredPosition3D, Vector3.zero, t);
                yield return null;
            }
            m_setInstantTransition = false;
            m_cachedButtonHighlight.ResetCanvasLayer();
        }

        public override void RemoveHighlighterFromScene()
        {
            if (!m_systemEnabled || !m_isButtonHighlightActive) return;
            if (m_currentlySelected != null && IsValidSelectableForNavigation(m_currentlySelected)) return;
            if (m_cachedButtonHighlight == null) return;
            m_cachedButtonHighlight.transform.SetParent(transform, true);
            m_cachedButtonHighlight.transform.localScale = Vector3.zero;
            this.SafeStopCoroutine(ref m_coroutine);
            m_cachedButtonHighlight.ReactivateBehaviours();
            FindAndSelectNewSelectable();
        }

        public void FindAndSelectNewSelectable()
        {
            SelectableBase selectable = TryGetCachedSelectable();
            m_setInstantTransition = true;
            if (selectable == null) return;
            SelectThis(selectable, true);
        }

        public override SelectableBase TryGetCachedSelectable()
        {
            if (m_lastKnownSelected != null && IsValidSelectableForNavigation(m_lastKnownSelected)) return m_lastKnownSelected;
            m_recentlySubmittedSelectables.RemoveAll(item => item == null);
            for (int i = m_recentlySubmittedSelectables.Count - 1; i >= 0; i--)
                if (IsValidSelectableForNavigation(m_recentlySubmittedSelectables[i])) return m_recentlySubmittedSelectables[i];
            return FindSelectable(Vector3.down, m_recoveryScreenOrigin, null, null);
        }

        public void AppReloading()
        {
            this.SafeStopCoroutine(ref m_coroutine);
            BlockFindSelectable = () => false;
            DisableSystem(false);
        }

        private void OnUpdateLastInputType(UIInputType lastInputType)
        {
            if (!m_systemActive || m_cachedLastInputType == lastInputType) return;
            m_cachedLastInputType = lastInputType;
            bool valid = m_inputBridge.DoesInputTypeRequireSelection(lastInputType);
            if (valid) { if (!m_systemEnabled) EnableSystem(); }
            else if (m_systemEnabled) DisableSystem(false);
        }

        public override void ActivateSystem()
        {
            m_systemActive = true;
            EnableSystemIfInputTypeIsValid(m_inputBridge.GetLastInputType());
        }

        public override void DeactivateSystem(bool isBeingDestroyed = false)
        {
            if (m_systemActive) { DisableSystem(isBeingDestroyed); m_systemActive = false; }
        }

        private void DisableSystem(bool isBeingDestroyed = false)
        {
            m_systemEnabled = false;
            this.SafeStopCoroutine(ref m_coroutine);
            if (m_cachedButtonHighlight != null && !isBeingDestroyed)
            {
                m_cachedButtonHighlight.gameObject.SetActive(false);
                m_cachedButtonHighlight.transform.SetParent(transform, true);
                m_isButtonHighlightActive = false;
            }
            m_inputBridge.SetHardwareCursorVisibility(true);
            if (m_currentlySelected == null) return;
            DeselectCurrentSelection();
        }

        private void EnableSystem()
        {
            m_systemEnabled = true;
            if (!m_isButtonHighlightActive) SpawnSelectedIndicator();
            FindAndSelectNewSelectable();
            m_inputBridge.SetHardwareCursorVisibility(false);
        }

        private bool EnableSystemIfInputTypeIsValid(UIInputType type)
        {
            bool valid = m_inputBridge.DoesInputTypeRequireSelection(type);
            if (valid && !m_systemEnabled) EnableSystem();
            return valid;
        }

