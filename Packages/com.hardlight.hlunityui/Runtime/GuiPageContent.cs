using System.Collections;
using Hardlight.Utils;
using Unity.IL2CPP.CompilerServices;
using UnityEngine;

namespace Hardlight
{
    [Il2CppSetOption(Option.NullChecks, false)]
    [Il2CppSetOption(Option.ArrayBoundsChecks, false)]
    public abstract class GuiPageContent : MonoBehaviour
    {
        private GuiPage parentPage;
        private UIOrientation m_cachedOrientation;
        private SystemRef<ScreenManager> m_screenManager;
        [SerializeField] protected GuiBackgroundManager.Active m_backgroundActive = GuiBackgroundManager.Active.NoChange;
        [Tooltip("Initial game object selected when page is shown")]
        [SerializeField] protected SelectableBase m_firstSelectedObject;
        [Tooltip("Alternative initial game objects that will be selected when page is shown if the prior option is null")]
        [SerializeField] private SelectableBase[] m_firstSelectedObjectAlternatives;
        [SerializeField] private bool m_firstSelectableInstantTransition;
        [Tooltip("Default to true, as most pageContent should be included automatically - dynamically switched pages should not")]
        [SerializeField] private bool m_includeInAutogeneratedContent = true;
        [SerializeField] private bool m_autoFindSelectableIfNoneSelected;
        private SelectableControllerBase m_selectableController;
        protected InputBridge m_inputBridge;
        private UIRuntimeConfiguration m_internalUIRuntimeConfiguration;

        // Original 06000140: this cache uses managed reference null semantics.
        public GuiPage ParentPage => parentPage = parentPage ?? GetComponentInParent<GuiPage>();

        // Original 06000141: an incompatible controller returns null.
        protected HLSelectableController m_hlSelectableController => m_selectableController as HLSelectableController;

        // Original 06000142: configuration lookup uses Unity object null semantics.
        protected UIRuntimeConfiguration m_uiRuntimeConfiguration
        {
            get
            {
                if (m_internalUIRuntimeConfiguration == null)
                    m_internalUIRuntimeConfiguration = ProcessManager.GetSystem<UIRuntimeConfiguration>(null, true);
                return m_internalUIRuntimeConfiguration;
            }
        }

        // Original 06000143: update the cached orientation before the virtual callback.
        protected virtual void EvaluateOrientation()
        {
            ScreenManager screenManager = m_screenManager?.GetSafe();
            if (screenManager != null && m_cachedOrientation != screenManager.Orientation)
            {
                m_cachedOrientation = screenManager.Orientation;
                ReactToOrientationChange();
            }
        }

        // Original 06000144 is a genuine empty virtual extension point.
        protected virtual void ReactToOrientationChange() { }

        // Original 06000145: configuration reads, subscription and singleton lookup
        // retain their order, including the lookup for a NoChange background.
        public virtual void OnShow(GuiPageParameters parameters)
        {
            m_autoFindSelectableIfNoneSelected |= m_uiRuntimeConfiguration.ShouldHighlightSelection;
            if (m_uiRuntimeConfiguration.ShouldAutoRotateScreen)
            {
                m_screenManager = ProcessManager.GetSystemRef<ScreenManager>(null, true);
                if (m_screenManager.IsValid())
                    m_screenManager.Get().OnOrientationChange += ReactToOrientationChange;
            }
            if (m_uiRuntimeConfiguration.ShouldHighlightSelection)
                m_selectableController = ProcessManager.GetSystemOfType<SelectableControllerBase>();
            m_inputBridge = m_uiRuntimeConfiguration.InputBridge;
            GuiBackgroundManager background = MonoSingleton<GuiBackgroundManager>.Instance;
            switch (m_backgroundActive)
            {
                case GuiBackgroundManager.Active.NoChange:
                    return;
                case GuiBackgroundManager.Active.Default:
                    background.SetUIBackgroundToDefault();
                    return;
                case GuiBackgroundManager.Active.Dark:
                    background.SetUIBackgroundToDark();
                    return;
                default:
                    background.SetUIBackgroundToNone();
                    return;
            }
        }

        // Original 06000146: forcing bypasses only the inactive-object check.
        // Interaction and input-module checks still apply; controller checks and
        // cached selection run only while selection highlighting is enabled.
        public bool SetSelectedGameObject(SelectableBase selectable, bool forceSelection = false)
        {
            if (m_uiRuntimeConfiguration.ShouldHighlightSelection)
            {
                m_selectableController = ProcessManager.GetSystemOfType<SelectableControllerBase>();
                if (m_selectableController == null || m_selectableController.ShouldBlockFindSelectable())
                    return false;
                if (selectable == null && m_autoFindSelectableIfNoneSelected)
                    selectable = m_selectableController.TryGetCachedSelectable();
            }
            if (selectable == null)
                return false;
            if (!selectable.gameObject.activeInHierarchy && !forceSelection)
                return false;
            if (!selectable.IsInteractable())
                return false;
            if (m_inputBridge == null || !m_inputBridge.InputModuleExists())
                return false;
            if (m_uiRuntimeConfiguration.ShouldHighlightSelection)
                m_selectableController.SelectThis(selectable, m_firstSelectableInstantTransition);
            else
                m_inputBridge.SetSelectedGameObjectWithMemory(selectable.gameObject, null);
            return true;
        }

        // Original 06000147 requires both active states before starting selection.
        public virtual void ShowComplete(GuiPageParameters parameters)
        {
            if (m_uiRuntimeConfiguration.ShouldHighlightSelection && gameObject.activeSelf && gameObject.activeInHierarchy)
                StartCoroutine(SelectFirstSelectable());
        }

        // Original 06000148 and natural owner 0200002f / 06000151..156.
        // The alternatives array is reread after each failed selection.
        protected IEnumerator SelectFirstSelectable()
        {
            yield return null;
            if (SetSelectedGameObject(m_firstSelectedObject, false))
                yield break;
            if (m_firstSelectedObjectAlternatives != null)
            {
                for (int i = 0; i < m_firstSelectedObjectAlternatives.Length; ++i)
                    if (SetSelectedGameObject(m_firstSelectedObjectAlternatives[i], false))
                        yield break;
            }
            SetSelectedGameObject(m_firstSelectedObject, true);
        }

        // Original 06000149 and natural owner 02000031 / 0600015d..162.
        protected IEnumerator SetSelectedGameObjectAfterOneFrame(HLSelectable selectable, bool forceSelection = false)
        {
            yield return null;
            SetSelectedGameObject(selectable, forceSelection);
        }

        // Original 0600014a uses the shared coroutine runner.
        public void Action_SetSelectedGameObject(HLSelectable selectable) => CoroutineUtils.RunCoroutine(SelectSelectable(selectable));

        // Original 0600014b and natural owner 02000030 / 06000157..15c.
        private IEnumerator SelectSelectable(HLSelectable selectable)
        {
            yield return null;
            if (!SetSelectedGameObject(selectable, true))
                HLOutput.LogError("GuiPageContent::SelectSelectable() Unable to select selectable!", null);
        }

        // Original 0600014c: remove only when autorotation is configured and the
        // existing system reference still holds a live Unity object.
        public virtual void OnHide(GuiPageParameters parameters, UISystemClosureReason reasonForClosure)
        {
            if (m_uiRuntimeConfiguration.ShouldAutoRotateScreen)
            {
                ScreenManager screenManager = m_screenManager?.GetSafe();
                if (screenManager != null)
                    screenManager.OnOrientationChange -= ReactToOrientationChange;
            }
        }

        // Original 0600014d retains the shipped method-name spelling.
        public bool ShouldBeIncludedInAutogeneratedContnt() => m_includeInAutogeneratedContent;

        // Original 0600014e / 0600014f are genuine empty virtual extension points.
        public virtual void OnEnter(GuiPageParameters parameters) { }
        public virtual void OnExit(GuiPageParameters parameters) { }

        // Original 06000150: field defaults are written before MonoBehaviour's constructor.
        protected GuiPageContent() { }
    }
}
