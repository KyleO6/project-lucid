using Hardlight.Utils;
using Unity.IL2CPP.CompilerServices;
using UnityEngine;
using UnityEngine.Events;

namespace Hardlight
{
    [RequireComponent(typeof(CanvasGroup))]
    [Il2CppSetOption(Option.ArrayBoundsChecks, false)]
    [Il2CppSetOption(Option.NullChecks, false)]
    public class SubPageContent : GuiPageContent
    {
        // Original 060001d3/d4: public auto-property; managed backing field precedes authored fields.
        public HubPage HubPage { get; set; }

        [SerializeField] private bool m_forceAdjustBackgroundBleedSizeOnRelocate = true;
        [SerializeField] private CanvasGroup m_canvasGroup;
        [SerializeField] private bool m_allowOpacityOverride;
        [SerializeField] public UnityEvent m_onCenter = new UnityEvent();
        [SerializeField] public UnityEvent m_onHide = new UnityEvent();
        [SerializeField] private UnityEvent m_onDragStarted = new UnityEvent();
        [SerializeField] protected GameObject[] m_objectsToActivateOnCenter = new GameObject[0];
        protected bool m_isCentered;
        private bool m_hubPageHasLoaded;

        // Original 060001d5 reads the serialized flag, initially true.
        public bool ForceAdjustBackgroundBleedSizeOnRelocate => m_forceAdjustBackgroundBleedSizeOnRelocate;

        // Original 060001d6: base callback then unguarded hide event, then flag and canvas.
        // An event exception prevents subsequent stores. Hub-loaded is not reset here.
        public override void OnHide(GuiPageParameters parameters, UISystemClosureReason reasonForClosure)
        {
            base.OnHide(parameters, reasonForClosure);
            m_onHide.Invoke();
            m_isCentered = false;
            if (m_canvasGroup != null)
                m_canvasGroup.alpha = 0f;
        }

        // Original 060001d7: direct centered helper, without a base OnShow/OnCenter call.
        public virtual void OnCenter(GuiPageParameters parameters) => PageIsCentred();

        // Original 060001d8: clear centered before the one managed-null-safe event.
        public void DragHasStarted()
        {
            m_isCentered = false;
            m_onDragStarted?.Invoke();
        }

        // Original 060001d9: mark loaded before conditionally rerunning centered effects.
        public void OnHubPageShowComplete()
        {
            m_hubPageHasLoaded = true;
            if (m_isCentered)
                PageIsCentred();
        }

        // Original 060001da: authored opt-in and Unity null; input float is not clamped.
        public void SetOpacity(float opacity)
        {
            if (!m_allowOpacityOverride || m_canvasGroup == null)
                return;
            m_canvasGroup.alpha = opacity;
        }

        // Original 060001db/dc: genuine empty virtual extension points.
        public virtual void Initialise() { }
        public virtual void Uninitialise() { }

        // Original 060001dd: flag first, then loaded gate; no guard for center event or array.
        // The field/array element are reread around SetActive; callbacks may replace the array.
        // Singleton lookup still occurs for NoChange; invalid enum bits route to None.
        private void PageIsCentred()
        {
            m_isCentered = true;
            if (!m_hubPageHasLoaded)
                return;
            m_onCenter.Invoke();
            for (int i = 0; i < m_objectsToActivateOnCenter.Length; ++i)
                if (m_objectsToActivateOnCenter[i] != null)
                    m_objectsToActivateOnCenter[i].SetActive(true);
            GuiBackgroundManager background = MonoSingleton<GuiBackgroundManager>.Instance;
            switch (m_backgroundActive)
            {
                case GuiBackgroundManager.Active.NoChange:
                    break;
                case GuiBackgroundManager.Active.Default:
                    background.SetUIBackgroundToDefault();
                    break;
                case GuiBackgroundManager.Active.Dark:
                    background.SetUIBackgroundToDark();
                    break;
                default:
                    background.SetUIBackgroundToNone();
                    break;
            }
            if (m_canvasGroup != null)
                m_canvasGroup.alpha = 1f;
        }

        // Original 060001de: force=true, three distinct events, fresh empty array;
        // normal base constructor retains its own background/autogenerated defaults.
        public SubPageContent() { }
    }
}
